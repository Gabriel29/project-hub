-- PostgreSQL identity baseline, executed by .NET through Npgsql.
CREATE SCHEMA IF NOT EXISTS identity;

-- Referenced tables precede dependent tables so foreign keys can be declared here.

CREATE TABLE identity."AspNetUsers" (
    "Id" text NOT NULL CONSTRAINT "PK_AspNetUsers" PRIMARY KEY,
    "DisplayName" text NOT NULL,
    "Activated" boolean NOT NULL,
    "Disabled" boolean NOT NULL,
    "UserName" character varying(256),
    "NormalizedUserName" character varying(256),
    "Email" character varying(256),
    "NormalizedEmail" character varying(256),
    "EmailConfirmed" boolean NOT NULL,
    "PasswordHash" text,
    "SecurityStamp" text,
    "ConcurrencyStamp" text,
    "PhoneNumber" text,
    "PhoneNumberConfirmed" boolean NOT NULL,
    "TwoFactorEnabled" boolean NOT NULL,
    "LockoutEnd" timestamp with time zone,
    "LockoutEnabled" boolean NOT NULL,
    "AccessFailedCount" integer NOT NULL,
    "Language" character varying(2) DEFAULT 'en'::character varying NOT NULL
);

CREATE TABLE identity."AspNetRoles" (
    "Id" text NOT NULL CONSTRAINT "PK_AspNetRoles" PRIMARY KEY,
    "Name" character varying(256),
    "NormalizedName" character varying(256),
    "ConcurrencyStamp" text
);

CREATE TABLE identity."AspNetRoleClaims" (
    "Id" integer NOT NULL CONSTRAINT "PK_AspNetRoleClaims" PRIMARY KEY,
    "RoleId" text NOT NULL,
    "ClaimType" text,
    "ClaimValue" text,
    CONSTRAINT "FK_AspNetRoleClaims_AspNetRoles_RoleId" FOREIGN KEY ("RoleId") REFERENCES identity."AspNetRoles"("Id") ON DELETE CASCADE
);

ALTER TABLE identity."AspNetRoleClaims" ALTER COLUMN "Id" ADD GENERATED BY DEFAULT AS IDENTITY (
    SEQUENCE NAME identity."AspNetRoleClaims_Id_seq"
    START WITH 1
    INCREMENT BY 1
    NO MINVALUE
    NO MAXVALUE
    CACHE 1
);

CREATE TABLE identity."AspNetUserClaims" (
    "Id" integer NOT NULL CONSTRAINT "PK_AspNetUserClaims" PRIMARY KEY,
    "UserId" text NOT NULL,
    "ClaimType" text,
    "ClaimValue" text,
    CONSTRAINT "FK_AspNetUserClaims_AspNetUsers_UserId" FOREIGN KEY ("UserId") REFERENCES identity."AspNetUsers"("Id") ON DELETE CASCADE
);

ALTER TABLE identity."AspNetUserClaims" ALTER COLUMN "Id" ADD GENERATED BY DEFAULT AS IDENTITY (
    SEQUENCE NAME identity."AspNetUserClaims_Id_seq"
    START WITH 1
    INCREMENT BY 1
    NO MINVALUE
    NO MAXVALUE
    CACHE 1
);

CREATE TABLE identity."AspNetUserLogins" (
    "LoginProvider" text NOT NULL,
    "ProviderKey" text NOT NULL,
    "ProviderDisplayName" text,
    "UserId" text NOT NULL,
    CONSTRAINT "PK_AspNetUserLogins" PRIMARY KEY ("LoginProvider", "ProviderKey"),
    CONSTRAINT "FK_AspNetUserLogins_AspNetUsers_UserId" FOREIGN KEY ("UserId") REFERENCES identity."AspNetUsers"("Id") ON DELETE CASCADE
);

CREATE TABLE identity."AspNetUserRoles" (
    "UserId" text NOT NULL,
    "RoleId" text NOT NULL,
    CONSTRAINT "PK_AspNetUserRoles" PRIMARY KEY ("UserId", "RoleId"),
    CONSTRAINT "FK_AspNetUserRoles_AspNetRoles_RoleId" FOREIGN KEY ("RoleId") REFERENCES identity."AspNetRoles"("Id") ON DELETE CASCADE,
    CONSTRAINT "FK_AspNetUserRoles_AspNetUsers_UserId" FOREIGN KEY ("UserId") REFERENCES identity."AspNetUsers"("Id") ON DELETE CASCADE
);

CREATE TABLE identity."AspNetUserTokens" (
    "UserId" text NOT NULL,
    "LoginProvider" text NOT NULL,
    "Name" text NOT NULL,
    "Value" text,
    CONSTRAINT "PK_AspNetUserTokens" PRIMARY KEY ("UserId", "LoginProvider", "Name"),
    CONSTRAINT "FK_AspNetUserTokens_AspNetUsers_UserId" FOREIGN KEY ("UserId") REFERENCES identity."AspNetUsers"("Id") ON DELETE CASCADE
);

CREATE TABLE identity."AccessLinks" (
    "Id" uuid NOT NULL CONSTRAINT "PK_AccessLinks" PRIMARY KEY,
    "Purpose" text NOT NULL,
    "ConsumedAt" timestamp with time zone,
    "UserId" text NOT NULL,
    "TokenHash" text NOT NULL,
    "ExpiresAt" timestamp with time zone NOT NULL,
    "RevokedAt" timestamp with time zone,
    "CreatedAt" timestamp with time zone NOT NULL,
    CONSTRAINT "FK_AccessLinks_AspNetUsers_UserId" FOREIGN KEY ("UserId") REFERENCES identity."AspNetUsers"("Id") ON DELETE CASCADE
);

CREATE TABLE identity."DataProtectionKeys" (
    "Id" integer NOT NULL CONSTRAINT "PK_DataProtectionKeys" PRIMARY KEY,
    "FriendlyName" text,
    "Xml" text
);

ALTER TABLE identity."DataProtectionKeys" ALTER COLUMN "Id" ADD GENERATED BY DEFAULT AS IDENTITY (
    SEQUENCE NAME identity."DataProtectionKeys_Id_seq"
    START WITH 1
    INCREMENT BY 1
    NO MINVALUE
    NO MAXVALUE
    CACHE 1
);

CREATE UNIQUE INDEX "EmailIndex" ON identity."AspNetUsers" USING btree ("NormalizedEmail");

CREATE UNIQUE INDEX "IX_AccessLinks_TokenHash" ON identity."AccessLinks" USING btree ("TokenHash");

CREATE INDEX "IX_AccessLinks_UserId" ON identity."AccessLinks" USING btree ("UserId");

CREATE INDEX "IX_AspNetRoleClaims_RoleId" ON identity."AspNetRoleClaims" USING btree ("RoleId");

CREATE INDEX "IX_AspNetUserClaims_UserId" ON identity."AspNetUserClaims" USING btree ("UserId");

CREATE INDEX "IX_AspNetUserLogins_UserId" ON identity."AspNetUserLogins" USING btree ("UserId");

CREATE INDEX "IX_AspNetUserRoles_RoleId" ON identity."AspNetUserRoles" USING btree ("RoleId");

CREATE UNIQUE INDEX "RoleNameIndex" ON identity."AspNetRoles" USING btree ("NormalizedName");

CREATE UNIQUE INDEX "UserNameIndex" ON identity."AspNetUsers" USING btree ("NormalizedUserName");
